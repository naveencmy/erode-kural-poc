def convert_bamini_to_unicode(text: str) -> str:
    """Convert Bamini font-encoded text string to standard Tamil Unicode."""
    if not text:
        return ""
    
    # If text is already mostly Unicode Tamil (>40% Tamil chars), return as is
    tamil_chars = len(re.findall(r"[\u0B80-\u0BFF]", text))
    if len(text) > 0 and (tamil_chars / len(text)) > 0.40:
        return text

    result = text
    for bamini, uni in BAMINI_RULES:
        result = result.replace(bamini, uni)
        
    return result
